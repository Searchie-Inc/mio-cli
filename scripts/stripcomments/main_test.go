const mixed = `// Copyright 2026 Example

// Package demo does things.
package demo

import (
	_ "embed"
	"os"
)

//go:embed body.txt
var body string

// Run runs.
//
//go:generate echo hi
func Run() {
	// first
	os.Unsetenv("A") //nolint:errcheck // because
	os.Unsetenv("B") //nolint
	/* block */
	x := 1 // trailing MIO-1
	_ = x
	// vendor: Stripe rejects empty ids https://docs.stripe.com/api
	_ = body
}

type T struct {
	A int // the A
	// B doc
	B int
}

func empty() {
	// nothing
}
`

const want = `// Copyright 2026 Example

package demo

import (
	_ "embed"
	"os"
)

//go:embed body.txt
var body string

//go:generate echo hi
func Run() {
	os.Unsetenv("A") //nolint:errcheck
	os.Unsetenv("B")
	x := 1
	_ = x
	// vendor: Stripe rejects empty ids https://docs.stripe.com/api
	_ = body
}

type T struct {
	A int
	B int
}

func empty() {
}
`

func TestStripKeepsOnlyAllowedComments(t *testing.T) {
	got, changed, err := strip("demo.go", []byte(mixed))
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Fatal("expected a change")
	}
	if string(got) != want {
		t.Fatalf("mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestStripIsIdempotent(t *testing.T) {
	once, _, err := strip("demo.go", []byte(mixed))
	if err != nil {
		t.Fatal(err)
	}
	twice, changed, err := strip("demo.go", once)
	if err != nil {
		t.Fatal(err)
	}
	if changed || !bytes.Equal(once, twice) {
		t.Fatalf("second run changed the file:\n%s", twice)
	}
}

func TestStripPreservesSyntaxTree(t *testing.T) {
	out, _, err := strip("demo.go", []byte(mixed))
	if err != nil {
		t.Fatal(err)
	}
	before, err := astDigest("demo.go", []byte(mixed))
	if err != nil {
		t.Fatal(err)
	}
	after, err := astDigest("demo.go", out)
	if err != nil {
		t.Fatal(err)
	}
	if before != after {
		t.Fatal("syntax tree changed")
	}
}

func TestDigestSeesCodeChanges(t *testing.T) {
	a, err := astDigest("a.go", []byte("package p\nvar x = 1\n"))
	if err != nil {
		t.Fatal(err)
	}
	b, err := astDigest("a.go", []byte("package p\nvar x = 2\n"))
	if err != nil {
		t.Fatal(err)
	}
	c, err := astDigest("a.go", []byte("package p\n\n// c\nvar   x   =   1\n"))
	if err != nil {
		t.Fatal(err)
	}
	if a == b {
		t.Fatal("digest ignores a literal change")
	}
	if a != c {
		t.Fatal("digest depends on comments or layout")
	}
}

func TestGeneratedFilesAreUntouched(t *testing.T) {
	src := "// Code generated by tool. DO NOT EDIT.\n\npackage p\n\n// F is.\nfunc F() {}\n"
	out, changed, err := strip("gen.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if changed || string(out) != src {
		t.Fatal("generated file was rewritten")
	}
	v, err := violations("gen.go", []byte(src))
	if err != nil || len(v) != 0 {
		t.Fatalf("generated file reported: %v %v", v, err)
	}
}

func TestViolationsNameEveryProhibitedComment(t *testing.T) {
	v, err := violations("demo.go", []byte(mixed))
	if err != nil {
		t.Fatal(err)
	}
	var texts []string
	for _, f := range v {
		texts = append(texts, f.Text)
	}
	joined := strings.Join(texts, "\n")
	for _, must := range []string{"// Package demo does things.", "// first", "//nolint", "/* block */", "// trailing MIO-1", "// the A", "// B doc", "// nothing", "// Run runs."} {
		if !strings.Contains(joined, must) {
			t.Errorf("not reported: %q", must)
		}
	}
	for _, mustNot := range []string{"go:embed", "go:generate", "vendor:", "Copyright"} {
		if strings.Contains(joined, mustNot) {
			t.Errorf("allowed comment reported: %q", mustNot)
		}
	}
}

func repoRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("go.mod not found")
		}
		dir = parent
	}
}

func TestRepoHasNoProhibitedComments(t *testing.T) {
	root := repoRoot(t)
	files, err := goFiles([]string{root})
	if err != nil {
		t.Fatal(err)
	}
	if len(files) < 100 {
		t.Fatalf("only %d Go files found under %s; the walk is broken", len(files), root)
	}
	for _, p := range files {
		src, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		v, err := violations(p, src)
		if err != nil {
			t.Fatalf("%s: %v", p, err)
		}
		for _, f := range v {
			rel, _ := filepath.Rel(root, p)
			t.Errorf("%s:%d: %s (rule: .claude/rules/no-comments.md; fix: go run ./scripts/stripcomments)", rel, f.Line, f.Text)
		}
	}
}

func TestStripKeepsTokensApart(t *testing.T) {
	src := "package p\n\nfunc f() {\n\tvar/*gap*/x = 1\n\t_ = x\n\tg()/*\n*/(h())\n}\n"
	got, _, err := strip("p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(got, []byte("var x = 1")) {
		t.Fatalf("tokens joined:\n%s", got)
	}
	if bytes.Contains(got, []byte("g()(h())")) {
		t.Fatalf("statement boundary lost:\n%s", got)
	}
}

func TestStripSpacedNolintIsStableAndIdempotent(t *testing.T) {
	src := "package p\n\nfunc f() {\n\tg() // nolint:errcheck\n}\n"
	once, _, err := strip("p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(once, []byte("g() //nolint:errcheck\n")) {
		t.Fatalf("nolint mangled:\n%s", once)
	}
	twice, changed, err := strip("p.go", once)
	if err != nil || changed || !bytes.Equal(once, twice) {
		t.Fatalf("not idempotent: changed=%v err=%v\n%s", changed, err, twice)
	}
}

func TestGeneratedMarkerInsideStringDoesNotExempt(t *testing.T) {
	src := "package p\n\n// stray\nvar s = `\n// Code generated by x. DO NOT EDIT.\n`\n"
	v, err := violations("p.go", []byte(src))
	if err != nil || len(v) != 1 {
		t.Fatalf("want 1 violation, got %v err=%v", v, err)
	}
	hdr := "// Code generated by x. DO NOT EDIT.\n\npackage p\n\n// kept\nvar a = 1\n"
	v, err = violations("p.go", []byte(hdr))
	if err != nil || len(v) != 0 {
		t.Fatalf("generated header must exempt: %v err=%v", v, err)
	}
}

