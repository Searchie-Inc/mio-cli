package client

// resolve.go — name/slug → id resolution for the user-facing flags and args.
//
// The CLI accepts a RAW id everywhere an id is expected; that path is and must
// stay first-class (it skips every list call and never touches the network for
// resolution). On top of that, this file lets a human-friendly NAME or SLUG be
// supplied instead, resolving it to the canonical id with a TARGETED, per-
// resource strategy.
//
// Design rules (a prior Codex review warned against a generic "list the first
// page and match" sweep, so the strategy is resource-aware):
//
//   - id passthrough: a value that is already id-shaped — a UUID (the real
//     production id, generated by the backend UUIDMixin as a uuid7) OR one of
//     the CLI's documented prefix conventions (team_/hub_/tag_/ctt_/tcid…) — is
//     returned unchanged with NO API call.
//   - server filter first: when the backend exposes a server-side filter for the
//     lookup (contacts support `filter[email]`, an exact normalized-email match),
//     use it — one narrow request, no client-side scan.
//   - list + match fallback: resources with no server-side name filter (teams,
//     hubs, tags) are listed with a sane page cap and matched client-side, slug
//     first then name, case-insensitively.
//   - never auto-pick an ambiguous name: 0 matches and >1 match are BOTH errors.
//     The >1 case lists the candidate id+name so the caller can disambiguate by
//     passing a raw id.
//   - per-process cache: a resolved (kind,value)→id pair is memoized so repeat
//     references in a single command (or a single process) don't re-list.

import (
	"context"
	"fmt"
	"net/url"
	"strings"
	"sync"
)

// resolveListCap bounds the list+match fallback for resources with no server
// filter. A team's tag/hub/team counts are small in practice; capping the page
// keeps the lookup a single bounded request instead of an unbounded sweep. If a
// name genuinely lives beyond this cap the user can always pass the raw id.
const resolveListCap = 200

// id-prefix conventions per resource. Production ids are bare UUIDs (uuid7 via
// the backend UUIDMixin), but the docs, examples, tests, and existing scripts
// use friendly prefixes — and BOTH spellings appear in the wild (e.g. a team is
// "team_…" in the README but "t_…" in the contract tests). A value carrying any
// of its resource's prefixes is treated as a first-class id (passthrough, no API
// call). Names/slugs do not look like these tokens, so prefix matching is safe.
var (
	teamIDPrefixes    = []string{"team_", "t_"}
	hubIDPrefixes     = []string{"hub_", "h_"}
	tagIDPrefixes     = []string{"tag_"}
	contactIDPrefixes = []string{"ctt_", "contact_", "tcid_", "tc_"}
)

// resolveCache memoizes (kind,value)→id for the lifetime of the process so a
// command that references the same name twice lists at most once. The CLI runs
// one command per process, so a simple mutex-guarded map is sufficient; there is
// no eviction because the process is short-lived.
type resolveCache struct {
	mu sync.Mutex
	m  map[string]string
}

func (c *resolveCache) get(key string) (string, bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.m == nil {
		return "", false
	}
	v, ok := c.m[key]
	return v, ok
}

func (c *resolveCache) put(key, id string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.m == nil {
		c.m = make(map[string]string)
	}
	c.m[key] = id
}

// cacheKey namespaces a cached lookup by kind + the optional parent scope (the
// team id for hub/tag/contact lookups) so a name that means different ids under
// different teams never collides.
func cacheKey(kind, scope, value string) string {
	return kind + "\x00" + scope + "\x00" + value
}

// isUUID reports whether s is a canonical 8-4-4-4-12 hex UUID (the real
// production id shape — the backend mints uuid7 values via UUIDMixin). Matching
// is case-insensitive and tolerant of the standard hyphenation only; a bare
// 32-hex value is intentionally NOT treated as a UUID because it is
// indistinguishable from an opaque name token.
func isUUID(s string) bool {
	if len(s) != 36 {
		return false
	}
	for i, r := range s {
		switch i {
		case 8, 13, 18, 23:
			if r != '-' {
				return false
			}
		default:
			if !isHexDigit(r) {
				return false
			}
		}
	}
	return true
}

func isHexDigit(r rune) bool {
	return (r >= '0' && r <= '9') || (r >= 'a' && r <= 'f') || (r >= 'A' && r <= 'F')
}

// hasIDPrefix reports whether value carries one of the given CLI id-prefix
// conventions (e.g. "team_", "hub_"). These prefixes are a CLI/docs convention
// — production ids are UUIDs — but they appear throughout the docs, examples,
// tests, and existing scripts, so a prefixed value must be treated as a
// first-class id (passthrough, no API call).
func hasIDPrefix(value string, prefixes ...string) bool {
	for _, p := range prefixes {
		if strings.HasPrefix(value, p) {
			return true
		}
	}
	return false
}

// isIDShaped reports whether value should be treated as an already-resolved id
// for a resource whose ids may carry any of the given CLI prefixes. A UUID is
// always id-shaped regardless of prefix.
func isIDShaped(value string, prefixes ...string) bool {
	return isUUID(value) || hasIDPrefix(value, prefixes...)
}

// ResolveTeam resolves a team NAME or SLUG to a team id. An id-shaped value
// (UUID or "team_…") is returned unchanged with no API call. Otherwise it lists
// the caller's teams and matches slug-first then name, case-insensitively.
//
// Teams have no server-side name filter, so this is a bounded list + match.
func (c *Client) ResolveTeam(ctx context.Context, value string) (string, error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "", fmt.Errorf("empty team identifier")
	}
	if isIDShaped(value, teamIDPrefixes...) {
		return value, nil
	}
	key := cacheKey("team", "", value)
	if id, ok := c.resolveCache.get(key); ok {
		return id, nil
	}

	col, err := c.List(ctx, "/api/teams", listCapQuery())
	if err != nil {
		return "", err
	}
	id, err := matchByNameOrSlug("team", "teams", value, col.Data)
	if err != nil {
		return "", err
	}
	c.resolveCache.put(key, id)
	return id, nil
}

// ResolveHub resolves a hub NAME or SLUG to a hub id within the given team. An
// id-shaped value (UUID or "hub_…") is returned unchanged with no API call.
