// ResolveContactByEmail resolves a contact EMAIL to a team-contact id within the
// given team. An id-shaped value (UUID or "ctt_…"/"tcid…") is returned unchanged
// with no API call. Otherwise it uses the backend's SERVER-SIDE `filter[email]`
// exact-match filter — a single narrow request, not a client-side scan.
//
// The contacts list endpoint normalizes the email server-side (trim + lower),
// so an exact match returns the single team-contact for that address.
func (c *Client) ResolveContactByEmail(ctx context.Context, teamID, email string) (string, error) {
	email = strings.TrimSpace(email)
	if email == "" {
		return "", fmt.Errorf("empty contact email")
	}
	// A raw contact id may legitimately be passed where an email is expected
	// (the flag accepts either); treat an id-shaped value as already resolved.
	// An address always contains '@', so it can never collide with an id token.
	if !strings.Contains(email, "@") && isIDShaped(email, contactIDPrefixes...) {
		return email, nil
	}
	if teamID == "" {
		return "", fmt.Errorf("cannot resolve contact %q by email without a team in context", email)
	}
	key := cacheKey("contact-email", teamID, strings.ToLower(email))
	if id, ok := c.resolveCache.get(key); ok {
		return id, nil
	}

	q := url.Values{}
	q.Set("filter[email]", email)
	q.Set("page[size]", itoaCap(resolveListCap))
	col, err := c.List(ctx, fmt.Sprintf("/api/teams/%s/contacts", teamID), q)
	if err != nil {
		return "", err
	}
	switch len(col.Data) {
	case 0:
		return "", fmt.Errorf("no contact with email %q — run 'mio contacts list'", email)
	case 1:
		id := col.Data[0].ID
		c.resolveCache.put(key, id)
		return id, nil
	default:
		// An exact-email filter should be unique; if the backend ever returns
		// multiple, surface them rather than silently picking one.
		return "", ambiguousError("contact", email, col.Data)
	}
}

// matchByNameOrSlug finds the single resource in data whose slug (preferred) or
// name matches value case-insensitively. It returns a not-found error on 0
// matches and an ambiguity error (listing candidates) on >1 — it NEVER picks one
// of several. kind is the singular human noun ("tag"); listCmd is the CLI list
// command noun used in the not-found hint ("tags").
func matchByNameOrSlug(kind, listCmd, value string, data []Resource) (string, error) {
	want := strings.ToLower(value)

	// Pass 1: slug (the canonical, unique-per-team identifier).
	var slugHits []Resource
	for _, r := range data {
		if slug, ok := r.Attributes["slug"].(string); ok && strings.ToLower(slug) == want {
			slugHits = append(slugHits, r)
		}
	}
	if len(slugHits) == 1 {
		return slugHits[0].ID, nil
	}
	if len(slugHits) > 1 {
		return "", ambiguousError(kind, value, slugHits)
	}

	// Pass 2: name (may be non-unique).
	var nameHits []Resource
	for _, r := range data {
		if name, ok := r.Attributes["name"].(string); ok && strings.ToLower(name) == want {
			nameHits = append(nameHits, r)
		}
	}
	switch len(nameHits) {
	case 0:
		return "", fmt.Errorf("no %s named %q — run 'mio %s list'", kind, value, listCmd)
	case 1:
		return nameHits[0].ID, nil
	default:
		return "", ambiguousError(kind, value, nameHits)
	}
}

// ambiguousError builds an error that lists every candidate id+name for an
// ambiguous name match so the operator can re-run with a raw id. It never
// resolves the ambiguity itself.
func ambiguousError(kind, value string, candidates []Resource) error {
	var sb strings.Builder
	fmt.Fprintf(&sb, "%s name %q is ambiguous — %d matches; pass a raw id instead:",
		kind, value, len(candidates))
	for _, r := range candidates {
		name, _ := r.Attributes["name"].(string)
		if name == "" {
			name, _ = r.Attributes["slug"].(string)
		}
		fmt.Fprintf(&sb, "\n  %s  %s", r.ID, name)
	}
	return fmt.Errorf("%s", sb.String())
}

// listCapQuery returns a query that caps the page size for a list+match
// resolution so the fallback is a single bounded request.
func listCapQuery() url.Values {
	q := url.Values{}
	q.Set("page[size]", itoaCap(resolveListCap))
	return q
}

// itoaCap renders a small positive cap as a decimal string without pulling in
// strconv (matching the dependency-free itoa helper in the cmd package).
func itoaCap(n int) string {
	if n <= 0 {
		return "1"
	}
	var buf [20]byte
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	return string(buf[i:])
}
